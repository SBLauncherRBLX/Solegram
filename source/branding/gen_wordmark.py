#!/usr/bin/env python3
"""Generates "Solegram" wordmark vector drawables (replacing Telegram's wordmark logos)."""
import os, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

HERE = os.path.dirname(os.path.abspath(__file__))
FONT = os.path.join(HERE, "..", "TMessagesProj", "src", "main", "assets", "fonts", "rextrabold.ttf")
RES = os.path.join(HERE, "..", "TMessagesProj", "src", "main", "res", "drawable")
TEXT = "Solegram"

font = TTFont(FONT)
gs = font.getGlyphSet()
cmap = font.getBestCmap()
upm = font["head"].unitsPerEm
hmtx = font["hmtx"]

def build(height_dp, out_name, tracking=0.0):
    # glyph outlines laid out on a baseline, y flipped (Android vectors are y-down)
    x = 0
    pen_paths = []
    bounds = BoundsPen(gs)
    for ch in TEXT:
        gname = cmap[ord(ch)]
        adv = hmtx[gname][0]
        svg = SVGPathPen(gs)
        gs[gname].draw(TransformPen(svg, (1, 0, 0, -1, x, 0)))
        pen_paths.append(svg.getCommands())
        gs[gname].draw(TransformPen(bounds, (1, 0, 0, -1, x, 0)))
        x += adv + tracking * upm
    xmin, ymin, xmax, ymax = bounds.bounds
    pad = upm * 0.02
    vw, vh = (xmax - xmin) + 2 * pad, (ymax - ymin) + 2 * pad
    tx, ty = -xmin + pad, -ymin + pad
    width_dp = height_dp * vw / vh
    data = " ".join(pen_paths)
    xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Solegram wordmark (generated by branding/gen_wordmark.py from Roboto) -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{width_dp:.3f}dp"
    android:height="{height_dp:.3f}dp"
    android:viewportWidth="{vw:.1f}"
    android:viewportHeight="{vh:.1f}">
    <group android:translateX="{tx:.1f}" android:translateY="{ty:.1f}">
        <path android:fillColor="#FFFFFFFF" android:pathData="{data}"/>
    </group>
</vector>
'''
    open(os.path.join(RES, out_name), "w").write(xml)
    print(out_name, f"{width_dp:.1f}x{height_dp:.1f}dp")

build(20.408922, "telegram_logo_2.xml")
build(19.0, "telegram_logo.xml")
