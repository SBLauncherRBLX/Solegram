#!/usr/bin/env python3
"""Generate the Solegram icon set and install it into TMessagesProj resources."""
import json, os, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "TMessagesProj", "src", "main", "res")
OUT = os.path.join(HERE, "out")

subprocess.check_call([sys.executable, os.path.join(HERE, "gen_icons.py"), OUT])

# Telegram's launcher slots -> Solegram palettes
SLOTS = {
    "ic_launcher": "sunset",   # DefaultIcon
    "icon_6_launcher": "gold",     # VintageIcon
    "icon_4_launcher": "ocean",    # AquaIcon
    "icon_3_launcher": "aurora",   # PremiumIcon
    "icon_5_launcher": "ember",    # TurboIcon
    "icon_2_launcher": "midnight", # NoxIcon
    "icon_7_launcher": "sakura",   # SakuraIcon
    "icon_8_launcher": "mint",     # MintIcon
    "icon_9_launcher": "lavender", # LavenderIcon
    "icon_10_launcher": "neon",    # NeonIcon
    "icon_11_launcher": "snow",    # SnowIcon
    "icon_12_launcher": "graphite",# GraphiteIcon
}

for f in os.listdir(os.path.join(OUT, "drawable")):
    shutil.copy(os.path.join(OUT, "drawable", f), os.path.join(RES, "drawable", f))

ADAPTIVE = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Solegram {palette} launcher icon (generated by branding/install_icons.py) -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/sg_icon_bg_{palette}" />
    <foreground android:drawable="@drawable/sg_icon_fg_{palette}" />
    <monochrome android:drawable="@drawable/sg_icon_fg_mono" />
</adaptive-icon>
'''
for slot, palette in SLOTS.items():
    for suffix in ("", "_round"):
        with open(os.path.join(RES, "mipmap-anydpi-v26", f"{slot}{suffix}.xml"), "w") as fh:
            fh.write(ADAPTIVE.format(palette=palette))

DENS = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
jobs = []
for slot, palette in SLOTS.items():
    for d, size in DENS.items():
        jobs.append({"svg": os.path.join(OUT, "svg", f"solegram_{palette}_squircle.svg"),
                     "out": os.path.join(RES, f"mipmap-{d}", f"{slot}.png"), "size": size, "pad": 0.06})
        jobs.append({"svg": os.path.join(OUT, "svg", f"solegram_{palette}_circle.svg"),
                     "out": os.path.join(RES, f"mipmap-{d}", f"{slot}_round.png"), "size": size, "pad": 0.04})
# Store/readme renders
os.makedirs(os.path.join(HERE, "png"), exist_ok=True)
for palette in set(SLOTS.values()):
    jobs.append({"svg": os.path.join(OUT, "svg", f"solegram_{palette}_squircle.svg"),
                 "out": os.path.join(HERE, "png", f"solegram_{palette}_512.png"), "size": 512, "pad": 0})
jobs.append({"svg": os.path.join(OUT, "svg", "solegram_sunset_square.svg"),
             "out": os.path.join(HERE, "png", "solegram_playstore_512.png"), "size": 512, "pad": 0})
jf = os.path.join(OUT, "jobs.json")
json.dump(jobs, open(jf, "w"))
subprocess.check_call(["node", os.path.join(HERE, "render_batch.js"), jf])
print(f"installed {len(SLOTS)} icon slots, rendered {len(jobs)} PNGs")
